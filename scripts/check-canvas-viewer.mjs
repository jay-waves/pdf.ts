import assert from 'node:assert/strict';
import { chromium } from '/home/jay-waves/.local/lib/node_modules/playwright/index.mjs';
import { fixture } from './pdf-editing-fixture.mjs';
const base = process.env.PDF_TEST_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(base);
  const transfer = await page.evaluateHandle(bytes => {
    const data = new DataTransfer(); data.items.add(new File([new Uint8Array(bytes)], 'canvas.pdf', { type: 'application/pdf' })); return data;
  }, [...fixture({ notes: true, content: '0.1 0.3 0.8 rg 30 40 230 200 re f\nBT /Helv 24 Tf 60 700 Td (Canvas viewer) Tj ET\n' })]);
  await page.locator('[aria-label="Choose or drop a PDF file"]').dispatchEvent('drop', { dataTransfer: transfer });
  await transfer.dispose();
  await page.locator('canvas[data-plane="tile"][data-painted="true"]').first().waitFor();
  assert.equal(await page.locator('.pdf-native-render-layer img').count(), 0);
  await page.mouse.move(640, 30);
  await page.getByRole('button', { name: 'Pin toolbar', exact: true }).click();
  await page.screenshot({ path: '/tmp/pdf-canvas-fit.png' });
  await page.getByRole('button', { name: 'Page', exact: true }).click();
  const zoom = page.getByRole('textbox', { name: 'Zoom percentage', exact: true });
  await zoom.fill('400%'); await zoom.press('Enter');
  await page.waitForFunction(() => document.querySelector('.pdf-page-surface')?.getBoundingClientRect().width > 2000);
  await page.waitForFunction(() => [...document.querySelectorAll('canvas[data-plane="tile"]')].some(c => Number(c.dataset.tileScale) >= 4));
  await page.waitForFunction(() => [...document.querySelectorAll('[data-canvas-tiles]')].every(p => p.dataset.fetching === '0'));
  const before = await page.evaluateHandle(() => [...document.querySelectorAll('canvas[data-plane="tile"]')]);
  const keys = await before.evaluate(canvases => canvases.map(c => c.dataset.tileKey));
  await page.mouse.move(700, 500); await page.mouse.wheel(0, 800);
  await page.waitForFunction(previous => [...document.querySelectorAll('canvas[data-plane="tile"]')].some(c => !previous.includes(c.dataset.tileKey)), keys);
  await page.waitForFunction(() => [...document.querySelectorAll('[data-canvas-tiles]')].every(p => p.dataset.fetching === '0'));
  assert.ok(await before.evaluate(canvases => canvases.some(c => c.isConnected)), 'pan must retain overlapping tiles instead of repainting the whole region');
  assert.ok(await before.evaluate(canvases => canvases.filter(c => c.isConnected).every(c => c.dataset.paintVersion === '1')), 'retained tiles must not be repainted');
  await before.dispose();
  await page.screenshot({ path: '/tmp/pdf-canvas-zoom.png' });
  assert.ok(await page.locator('canvas').evaluateAll(canvases => canvases.every(c => c.dataset.plane !== "tile" || (c.width <= 773 && c.height <= 773))));
  await page.getByRole('button', { name: 'Rotate', exact: true }).click();
  await page.getByRole('button', { name: 'Presentation mode', exact: true }).click();
  await page.locator('section[data-viewer-presentation] canvas[data-painted="true"]').first().waitFor();
  await page.screenshot({ path: '/tmp/pdf-canvas-presentation.png' });
  const presentationCanvases = await page.evaluateHandle(() => [...document.querySelectorAll('section[data-viewer-presentation] canvas')]);
  await page.keyboard.press('Escape');
  await page.locator('section[data-viewer-presentation]').waitFor({ state: 'detached' });
  const released = await presentationCanvases.evaluate(canvases => canvases.map(c => ({ connected: c.isConnected, width: c.width, height: c.height, plane: c.dataset.plane })));
  assert.ok(released.length > 0 && released.every(c => !c.connected && c.width === 0 && c.height === 0), JSON.stringify({ released, errors }));
  await presentationCanvases.dispose();
  assert.deepEqual(errors, []);
  console.log('PASS Canvas viewer fit, 400% zoom, tile reuse on pan, rotation, presentation, tile pixel bound and backing-store release.');
} finally { await browser.close(); }
